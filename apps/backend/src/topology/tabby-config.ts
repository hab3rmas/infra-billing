// Tabby config sections (`profiles` and `groups`) from the topology: a folder tree like the one an
// owner builds by hand, and a flag icon per country. Pure (no Nest / Prisma imports).
//
// Layout per map (the root folder is the project or map name):
//   <root>/                    infrastructure: panel, subscription page, bots, monitoring…
//     Nodes/                   exit servers that no bridge feeds
//       <bridge>-Bridge/       a bridge and the exits behind it
// Only what is known goes in: host, port, user (when set explicitly). Never a password or a key:
// the authentication is chosen in Tabby.

import { createHash } from 'node:crypto';
import { flagIcon } from './tabby-flags';

export interface TabbyItem {
  uuid: string;
  name: string;
  role: string;
  country: string | null;
  host: string;
  port: number;
  /** Only an explicitly configured user; the panel default is not forced on Tabby. */
  user: string | null;
  /** The bridge node that feeds this node, when it is behind one. */
  bridgeUuid: string | null;
  /** Folder the node belongs under: the project or map name. */
  rootName: string;
}

export interface TabbyGroup {
  id: string;
  name: string;
  icon: string;
  color?: string;
  parentGroupId?: string;
}

export interface TabbyProfile {
  id: string;
  name: string;
  icon: string;
  group?: string;
  host: string;
  port?: number;
  user?: string;
}

const INFRA_NOT = new Set(['bridge', 'entry', 'exit', 'relay']);

/** A stable uuid derived from a seed: the same folder gets the same id on every export. */
export function stableUuid(seed: string): string {
  const h = createHash('sha1').update(seed).digest('hex');
  const v = ((Number.parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${v}${h.slice(18, 20)}-${h.slice(20, 32)}`;
}

const slug = (s: string): string => s.trim().replace(/\s+/g, '-');

export const profileId = (name: string, uuid: string): string =>
  `ssh:custom:${slug(name) || 'host'}:${uuid}`;

export function layoutTabby(items: TabbyItem[]): {
  groups: TabbyGroup[];
  profiles: TabbyProfile[];
} {
  const groups = new Map<string, TabbyGroup>();
  const profiles: TabbyProfile[] = [];
  const group = (g: TabbyGroup): string => {
    if (!groups.has(g.id)) groups.set(g.id, g);
    return g.id;
  };
  const byUuid = new Map(items.map((i) => [i.uuid, i]));

  const add = (it: TabbyItem, groupId: string | undefined) => {
    profiles.push({
      id: profileId(it.name, it.uuid),
      name: it.name,
      icon: flagIcon(it.country),
      ...(groupId ? { group: groupId } : {}),
      host: it.host,
      ...(it.port !== 22 ? { port: it.port } : {}),
      ...(it.user ? { user: it.user } : {}),
    });
  };

  const roots = [...new Set(items.map((i) => i.rootName))];
  for (const rootName of roots) {
    const mine = items.filter((i) => i.rootName === rootName);
    const rootId = stableUuid(`group:${rootName}`);
    const root = (): string =>
      group({ id: rootId, name: rootName, icon: 'far fa-folder', color: '#6600ff' });
    const nodesGroup = (): string =>
      group({
        id: stableUuid(`group:${rootName}:Nodes`),
        name: 'Nodes',
        icon: 'far fa-folder',
        parentGroupId: root(),
      });

    const bridgeGroup = (b: TabbyItem): string =>
      group({
        id: stableUuid(`group:${rootName}:bridge:${b.uuid}`),
        name: `${b.name}-Bridge`,
        icon: 'far fa-clone',
        color: '#009dff',
        parentGroupId: nodesGroup(),
      });

    for (const it of mine) {
      if (!INFRA_NOT.has(it.role)) {
        add(it, root());
        continue;
      }
      const bridge = it.bridgeUuid ? byUuid.get(it.bridgeUuid) : undefined;
      if (it.role === 'bridge') {
        const hasExits = mine.some((x) => x.bridgeUuid === it.uuid);
        add(it, hasExits ? bridgeGroup(it) : nodesGroup());
      } else if (bridge && bridge.rootName === rootName) {
        add(it, bridgeGroup(bridge));
      } else {
        add(it, nodesGroup());
      }
    }
  }
  return { groups: [...groups.values()], profiles };
}

