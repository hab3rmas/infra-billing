/** A YAML double-quoted scalar (JSON string syntax is a subset of YAML's). */
export const yq = (s: string): string => JSON.stringify(s);

export function renderTabbyYaml(doc: { groups: TabbyGroup[]; profiles: TabbyProfile[] }): string {
  const out = [
    '# Generated by Infra Billing from the topology. Replace the `profiles:` and `groups:` sections of',
    '# the Tabby config.yaml with these (or merge them: scripts/tabby-merge.mjs keeps your keys).',
    '# No passwords or keys: choose the authentication in Tabby.',
    'profiles:',
  ];
  for (const p of doc.profiles) {
    out.push(
      '  - type: ssh',
      `    name: ${yq(p.name)}`,
      `    icon: ${yq(p.icon)}`,
      '    options:',
      `      host: ${yq(p.host)}`,
      ...(p.port ? [`      port: ${p.port}`] : []),
      ...(p.user ? [`      user: ${yq(p.user)}`] : []),
      '      algorithms: {}',
      '      input: {}',
      '    weight: -1',
      `    id: ${yq(p.id)}`,
      ...(p.group ? [`    group: ${yq(p.group)}`] : []),
    );
  }
  out.push('groups:');
  for (const g of doc.groups) {
    out.push(
      `  - id: ${yq(g.id)}`,
      `    name: ${yq(g.name)}`,
      `    icon: ${yq(g.icon)}`,
      ...(g.color ? [`    color: ${yq(g.color)}`] : []),
      ...(g.parentGroupId ? [`    parentGroupId: ${yq(g.parentGroupId)}`] : []),
    );
  }
  return `${out.join('\n')}\n`;
}
