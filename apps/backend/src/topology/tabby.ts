// Pure helpers for the Tabby export (no Nest / Prisma imports, unit-testable).
//
// Format of a Tabby `config.yaml` SSH profile (tabby-ssh, SSHProfile): `type: ssh`, `name`, `group`,
// `options: { host, port, user }`. Never a password or a key. `id` follows Tabby's own scheme
// `ssh:custom:<slug>:<uuid>`; the node uuid keeps it stable between exports.

export interface TabbyNodeInput {
  uuid: string;
  /** Exact name for the profile (tabbyProfile, else label, else service name). */
  name: string;
  group: string;
  host: string;
  port: number;
  user: string;
}

/** A YAML double-quoted scalar. JSON string syntax is a subset of YAML's, so this is always valid. */
export const yamlString = (s: string): string => JSON.stringify(s);

const slug = (s: string): string =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'host';

/** Make profile names unique: a second "madkid" becomes "madkid (2)". */
export function uniqueNames(inputs: { uuid: string; name: string }[]): Map<string, string> {
  const used = new Map<string, number>();
  const out = new Map<string, string>();
  for (const i of inputs) {
    const n = (used.get(i.name) ?? 0) + 1;
    used.set(i.name, n);
    out.set(i.uuid, n === 1 ? i.name : `${i.name} (${n})`);
  }
  return out;
}

export function buildTabbyYaml(nodes: TabbyNodeInput[]): string {
  const lines = [
    '# Generated by Infra Billing. Paste the block into the `profiles:` list of Tabby config.yaml.',
    '# No passwords or keys are included: set the authentication in Tabby.',
    'profiles:',
  ];
  for (const n of nodes) {
    lines.push(
      `  - id: ${yamlString(`ssh:custom:${slug(n.name)}:${n.uuid}`)}`,
      '    type: ssh',
      `    name: ${yamlString(n.name)}`,
      `    group: ${yamlString(n.group)}`,
      '    options:',
      `      host: ${yamlString(n.host)}`,
      `      port: ${n.port}`,
      `      user: ${yamlString(n.user)}`,
    );
  }
  return `${lines.join('\n')}\n`;
}
